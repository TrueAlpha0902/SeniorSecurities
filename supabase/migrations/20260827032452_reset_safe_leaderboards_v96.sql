-- SeniorSecurities v96
-- Reset-safe learning generations, distinct-question leaderboard metrics, and
-- idempotent practice-time events. The leaderboard remains securities-scoped;
-- foreign-exchange progress does not currently feed these statistics.

create table if not exists public.user_learning_reset_state (
  user_id uuid not null references auth.users(id) on delete cascade,
  exam_id text not null check (exam_id in ('senior-securities', 'junior-foreign-exchange')),
  data_generation bigint not null default 0 check (data_generation >= 0),
  wrong_generation bigint not null default 0 check (wrong_generation >= 0),
  last_mode text check (last_mode in ('wrong', 'restart', 'complete')),
  last_data_mode text check (last_data_mode in ('restart', 'complete')),
  last_request_id uuid,
  reset_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, exam_id)
);

create table if not exists public.user_learning_reset_requests (
  user_id uuid not null references auth.users(id) on delete cascade,
  request_id uuid not null,
  scope text not null check (scope in ('senior-securities', 'junior-foreign-exchange', 'all')),
  mode text not null check (mode in ('wrong', 'restart', 'complete')),
  result jsonb not null,
  created_at timestamptz not null default now(),
  primary key (user_id, request_id)
);

