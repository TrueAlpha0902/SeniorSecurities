  inserted_count integer := 0;
  recorded_seconds bigint := 0;
  first_recorded_at timestamptz;
  allowed_seconds bigint := 60;
begin
  if current_user_id is null then raise exception '請先登入。'; end if;
  if lower(trim(coalesce(p_exam_id, ''))) <> 'senior-securities' then
    raise exception 'invalid exam_id';
  end if;
  if p_event_id is null then raise exception 'event_id is required'; end if;
  if safe_seconds <= 0 or safe_seconds > 60 then
    raise exception 'practice event seconds must be between 1 and 60';
