select format(
  'fx-%s-%s-%s',
  session_number,
  subject,
  lpad(question_number::text, 3, '0')
), 'junior-foreign-exchange'
from generate_series(23, 47) as session_number
cross join lateral (
  select 'remittance'::text as subject, question_number
  from generate_series(1, 50) as question_number
  union all
  select 'trade'::text as subject, question_number
  from generate_series(1, 80) as question_number
) as questions
on conflict (question_id) do update set exam_id = excluded.exam_id;

do $$
declare
  target_table text;
  unknown_count bigint;
  invalid_image_count bigint;
begin
  foreach target_table in array array[
    'user_answer_records',
    'user_wrong_records',
    'user_favorite_records'
  ] loop
    execute format(
      'select count(*) from public.%I records left join public.leaderboard_question_catalog catalog on catalog.question_id = records.question_id where catalog.question_id is null',
      target_table
    ) into unknown_count;
    if unknown_count > 0 then
      raise exception '% contains % question ids outside the canonical catalog', target_table, unknown_count;
    end if;
    execute format(
      'update public.%I records set exam_id = catalog.exam_id from public.leaderboard_question_catalog catalog where catalog.question_id = records.question_id',
      target_table
    );
  end loop;

  select count(*) into invalid_image_count
  from public.user_image_quiz_sessions sessions
  where case
    when jsonb_typeof(sessions.question_ids) <> 'array' then true
    when jsonb_array_length(sessions.question_ids) < 1 then true
    when jsonb_array_length(sessions.question_ids) > 200 then true
    else exists (
        select 1
        from jsonb_array_elements_text(sessions.question_ids) ids(question_id)
        left join public.leaderboard_question_catalog catalog
          on catalog.question_id = ids.question_id
        where catalog.question_id is null
      ) or (
        select count(distinct catalog.exam_id)
        from jsonb_array_elements_text(sessions.question_ids) ids(question_id)
        join public.leaderboard_question_catalog catalog
          on catalog.question_id = ids.question_id
      ) <> 1
  end;
  if invalid_image_count > 0 then
    raise exception 'user_image_quiz_sessions contains % invalid or mixed-scope rows', invalid_image_count;
  end if;

  update public.user_image_quiz_sessions sessions
  set exam_id = (
    select min(catalog.exam_id) as exam_id
    from jsonb_array_elements_text(sessions.question_ids) ids(question_id)
    join public.leaderboard_question_catalog catalog
      on catalog.question_id = ids.question_id
  );

  update public.user_quiz_progress set exam_id = 'senior-securities';
  update public.user_quiz_sessions set exam_id = 'senior-securities';
end $$;

