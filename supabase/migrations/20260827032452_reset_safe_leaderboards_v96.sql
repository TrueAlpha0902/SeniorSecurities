-- Every synchronized learning row carries the generation of the browser that
-- produced it. This makes stale tabs and offline devices fail closed after a
-- reset instead of recreating records that the reset transaction removed.
do $$
declare
  target_table text;
begin
  foreach target_table in array array[
    'user_answer_records',
    'user_wrong_records',
    'user_favorite_records',
    'user_quiz_progress',
    'user_quiz_sessions',
    'user_image_quiz_sessions'
  ] loop
    execute format(
      'alter table public.%I add column if not exists exam_id text not null default ''senior-securities''',
      target_table
    );
    execute format(
      'alter table public.%I add column if not exists reset_generation bigint not null default 0',
      target_table
    );
  end loop;
end $$;

do $$
declare
  target_table text;
begin
  foreach target_table in array array[
    'user_answer_records',
    'user_wrong_records',
    'user_favorite_records',
    'user_quiz_progress',
    'user_quiz_sessions',
    'user_image_quiz_sessions'
  ] loop
    execute format('alter table public.%I drop constraint if exists %I', target_table, target_table || '_exam_id_v96_check');
    execute format(
      'alter table public.%I add constraint %I check (exam_id in (''senior-securities'', ''junior-foreign-exchange''))',
      target_table,
      target_table || '_exam_id_v96_check'
    );
    execute format('alter table public.%I drop constraint if exists %I', target_table, target_table || '_reset_generation_v96_check');
    execute format(
      'alter table public.%I add constraint %I check (reset_generation >= 0)',
      target_table,
      target_table || '_reset_generation_v96_check'
    );
    execute format(
      'create index if not exists %I on public.%I (user_id, exam_id, reset_generation)',
      target_table || '_reset_scope_v96_idx',
      target_table
    );
  end loop;
end $$;

